package de.codepath.backend.evaluation;

/** Die drei Teile einer Bewertungsrunde. */
public enum EvaluationPart {
    /** Schülerinnen und Schüler schätzen sich selbst ein */
    SELF,
    /** Schülerinnen und Schüler bewerten den Unterricht */
    LESSON,
    /** Die Lehrkraft bewertet jede Schülerin und jeden Schüler */
    TEACHER
}
